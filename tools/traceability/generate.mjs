/**
 * Generates FEATURE_TRACEABILITY.md from requirements.mjs + the check library + status.mjs.
 * Run: npm run traceability   (uses tsx to import the TypeScript check library)
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { REQUIREMENTS } from './requirements.mjs';
import { STATUS, CHECK_STATUS, PHASE_NOTE, DEFAULT_BY_PHASE } from './status.mjs';
import { CHECKS } from '../../packages/shared/src/checks/library.ts';

const here = dirname(fileURLToPath(import.meta.url));
const VALID = ['NOT STARTED', 'IN PROGRESS', 'IMPLEMENTED', 'TESTED', 'BLOCKED', 'PARTIAL'];

const checkReqs = CHECKS.map((c) => ({
  id: `PDF-CHK-${c.id}`,
  src: `p${c.pdfRef.page} §${c.pdfRef.section}`,
  desc: `${c.name} — ${c.detects} [Default severity: ${c.defaultSeverityText}]`,
  fe: `/modules/${c.module === 'ai_compliance' ? 'ai-compliance' : c.module} check table`,
  api: `check ${c.id}; sources: ${c.dataSources.join(', ')}`,
  roles: 'Admin, SEO, Dev (view)',
  phase: 'P1+P2',
}));

const all = [...REQUIREMENTS, ...checkReqs];
const ids = new Set();
for (const r of all) {
  if (ids.has(r.id)) throw new Error(`Duplicate requirement id ${r.id}`);
  ids.add(r.id);
}
const screens = REQUIREMENTS.filter((r) => r.id.startsWith('CUS-SCR-')).length;
if (screens !== 83) throw new Error(`Expected 83 screen requirements (prompt §4.2), found ${screens}`);

function statusFor(r) {
  if (STATUS[r.id]) return STATUS[r.id];
  if (r.id.startsWith('PDF-CHK-')) return CHECK_STATUS(r.id.replace('PDF-CHK-', ''));
  return DEFAULT_BY_PHASE(r);
}

const rows = all.map((r) => ({ ...r, ...statusFor(r) }));
for (const r of rows) if (!VALID.includes(r.status)) throw new Error(`Invalid status ${r.status} for ${r.id}`);

const counts = Object.fromEntries(VALID.map((s) => [s, rows.filter((r) => r.status === s).length]));
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

const sections = [
  ['PDF §1–§3 · Purpose, architecture, crawl strategy, tiers & severity', (r) => /^PDF-(1|2|3)\./.test(r.id)],
  ['PDF §4–§10 · Check library (one row per PDF table row)', (r) => r.id.startsWith('PDF-CHK-') || r.id === 'PDF-4.0'],
  ['PDF §10 · AI-content compliance extras & custom rule builder', (r) => r.id.startsWith('PDF-10.')],
  ['PDF §11 · Smart Recommendation Engine, Fix Cards, allocation', (r) => r.id.startsWith('PDF-11.')],
  ['PDF §12 · Reporting, alerting & team workflow', (r) => r.id.startsWith('PDF-12.')],
  ['PDF §13–§14 · Opportunity engine & scoring', (r) => /^PDF-1[34]\./.test(r.id)],
  ['PDF §15 · Data sources & access requirements', (r) => r.id.startsWith('PDF-15.')],
  ['PDF §16 · Rollout deliverables & acceptance criteria', (r) => r.id.startsWith('PDF-16.')],
  ['PDF §17 · Governance & guardrails', (r) => r.id.startsWith('PDF-17.')],
  ['PDF Appendix A · Issue taxonomy', (r) => r.id.startsWith('PDF-A.')],
  ['Prompt §4.2 · Required screens (83)', (r) => r.id.startsWith('CUS-SCR-')],
  ['Prompt §4.1/§7 · Design, UX & frontend architecture', (r) => r.id.startsWith('CUS-UX-')],
  ['Prompt §4.3 · Roles & role-aware experiences', (r) => r.id.startsWith('CUS-ROLE-')],
  ['Prompt §6 · Task management workflow', (r) => r.id.startsWith('CUS-TASK-')],
  ['Prompt §9 · Backend', (r) => r.id.startsWith('CUS-BE-')],
  ['Prompt §2/§7/§9/§14 · Documentation, process & database gate', (r) => r.id.startsWith('CUS-DOC-') || r.id.startsWith('CUS-DB-')],
];

let md = `# FEATURE_TRACEABILITY — DeoDap SEO Sentinel

> Generated by \`npm run traceability\` from \`tools/traceability/requirements.mjs\`, the check library
> (\`packages/shared/src/checks/library.ts\`) and \`tools/traceability/status.mjs\`. Do not hand-edit this file.
>
> Sources: \`docs/seotooldocs.pdf\` (22 pages — page refs "pN §x") and \`docs/MASTER_BUILD_PROMPT.md\` ("prompt §x").
> Phases: **P1** = frontend, **P2** = backend (in-memory repositories), **P3** = database (not started — awaits explicit authorization).

${PHASE_NOTE}

## Summary

| Status | Count |
|---|---|
${VALID.map((s) => `| ${s} | ${counts[s]} |`).join('\n')}
| **Total requirements** | **${rows.length}** |

Status meanings: **TESTED** = implemented and covered by an automated test or recorded verification (evidence column cites it).
**IMPLEMENTED** = code exists and works in the app, not covered by a dedicated automated test. **PARTIAL** = some of the requirement
works; the gap is stated. **BLOCKED** = cannot be completed without credentials/access/infrastructure (stated). Sample (DEMO) data never
counts as "connected to live data".

`;
for (const [title, pred] of sections) {
  const list = rows.filter(pred);
  if (!list.length) continue;
  md += `\n## ${title}\n\n| ID | Source | Requirement | Frontend | API / service | Roles | Phase | Status | Evidence / test | Dependency / blocker |\n|---|---|---|---|---|---|---|---|---|---|\n`;
  for (const r of list) md += `| ${r.id} | ${esc(r.src)} | ${esc(r.desc)} | ${esc(r.fe)} | ${esc(r.api)} | ${esc(r.roles)} | ${r.phase} | **${r.status}** | ${esc(r.evidence)} | ${esc(r.blocker)} |\n`;
}
const unassigned = rows.filter((r) => !sections.some(([, p]) => p(r)));
if (unassigned.length) throw new Error(`Requirements not in any section: ${unassigned.map((r) => r.id).join(', ')}`);

const out = resolve(here, '../../FEATURE_TRACEABILITY.md');
writeFileSync(out, md);
console.log(`Wrote ${out}: ${rows.length} requirements`, counts);
