import { Link } from 'react-router-dom';
import { ArrowUpRight } from 'lucide-react';
import type { OpportunityItem } from '@sentinel/shared';
import { api } from '@/api/client';
import { useApiQuery } from '@/api/hooks';
import { useAuth } from '@/auth/AuthContext';
import { Async, Badge, DemoBadge, EmptyState, Notice, PageHeader, Panel, Stat } from '@/components/ui/primitives';
import { ChipGroup, ClearFilters, FilterSelect, useUrlFilters } from '@/components/ui/filters';
import { SourceBadge } from '@/components/domain/badges';
import { OPP_KIND_LABELS, OPP_KIND_SCREEN, OppStatusBadge, OpportunityActions, SiteUrl } from '@/components/opportunities/shared';
import { fmtDate, fmtNum, fmtRelative } from '@/lib/format';

const KEYS = ['kind', 'status', 'group'] as const;
type Kind = OpportunityItem['kind'];
type Status = OpportunityItem['status'];
const KINDS = Object.keys(OPP_KIND_LABELS) as Kind[];
const STATUSES: { value: Status; label: string }[] = [
  { value: 'open', label: 'Open' },
  { value: 'task_created', label: 'Actioned' },
  { value: 'dismissed', label: 'Dismissed' },
];

export default function OpportunitiesBoardPage() {
  const q = useApiQuery(['opportunities'], () => api.listOpportunities());
  return (
    <div>
      <PageHeader
        title="Opportunities"
        description="Growth opportunities from every module — striking-distance queries, CTR rewrites, keyword gaps, briefs, link prospects, unlinked mentions, PAA/snippet targets, seasonal prompts, digital PR and citation gaps — ranked by value (PDF §12.3, Appendix A opportunity class)."
        meta={<DemoBadge />}
      />
      <Async q={q} rows={10}>{(items) => <Board items={items} />}</Async>
    </div>
  );
}

function Board({ items }: { items: OpportunityItem[] }) {
  const f = useUrlFilters(KEYS);
  const { can } = useAuth();
  const kinds = f.getList('kind') as Kind[];
  const statusParam = f.get('status');
  const status: Status[] = statusParam === 'all' ? STATUSES.map((s) => s.value) : statusParam ? [statusParam as Status] : ['open'];
  const grouped = f.get('group') === '1';
  const presentKinds = KINDS.filter((k) => items.some((o) => o.kind === k));
  const visible = items
    .filter((o) => (!kinds.length || kinds.includes(o.kind)) && status.includes(o.status))
    .sort((a, b) => b.value - a.value);

  const open = items.filter((o) => o.status === 'open');
  const converted = items.filter((o) => o.status === 'task_created').length;
  const dismissed = items.filter((o) => o.status === 'dismissed').length;

  return (
    <div className="space-y-5">
      <div className="grid grid-cols-2 gap-3 md:grid-cols-4">
        <Stat label="Open opportunities" value={open.length} tone="signal" />
        <Stat label="Open value (ranking units)" value={fmtNum(open.reduce((s, o) => s + o.value, 0))} hint="Relative score used for ordering" />
        <Stat label="Actioned" value={converted} />
        <Stat label="Dismissed" value={dismissed} />
      </div>

      {!can('opportunities.manage') && (
        <Notice tone="neutral">You can view opportunities. Converting or dismissing them needs the <span className="font-mono">opportunities.manage</span> permission (Admin or SEO Specialist).</Notice>
      )}

      <Panel bodyClassName="space-y-3 p-3">
        <ChipGroup
          label="Kind"
          value={kinds}
          onChange={(v) => f.set('kind', v)}
          options={presentKinds.map((k) => ({ value: k, label: `${OPP_KIND_LABELS[k]} (${items.filter((o) => o.kind === k && status.includes(o.status)).length})` }))}
        />
        <div className="flex flex-wrap items-center gap-3">
          <FilterSelect
            label="Status"
            allLabel="Open (default)"
            value={statusParam === 'open' ? '' : statusParam}
            onChange={(v) => f.set('status', v)}
            options={[...STATUSES.filter((s) => s.value !== 'open'), { value: 'all', label: 'All statuses' }]}
          />
          <label className="flex items-center gap-1.5 text-xs text-muted">
            <input type="checkbox" className="h-4 w-4 accent-[#7650D8]" checked={grouped} onChange={(e) => f.set('group', e.target.checked ? '1' : '')} />
            Group by kind
          </label>
          <span className="text-xs text-muted">Sorted by value, highest first</span>
          <ClearFilters show={f.active} onClear={f.clear} />
        </div>
      </Panel>

      {!visible.length ? (
        <Panel>
          <EmptyState
            title={status.length === 1 && status[0] === 'open' && !kinds.length ? 'No open opportunities' : 'No opportunities match these filters'}
            description="Opportunities are generated by the daily crawl and the weekly keyword, backlink and AI-visibility jobs. Clear the filters or include converted and dismissed items."
          />
        </Panel>
      ) : grouped ? (
        <div className="space-y-5">
          {presentKinds.filter((k) => visible.some((o) => o.kind === k)).map((k) => {
            const rows = visible.filter((o) => o.kind === k);
            return (
              <Panel
                key={k}
                title={<>{OPP_KIND_LABELS[k]} <span className="ml-1 text-sm font-normal text-muted">{rows.length}</span></>}
                actions={<Link to={OPP_KIND_SCREEN[k].href} className="inline-flex items-center gap-1 text-sm text-signal hover:underline">{OPP_KIND_SCREEN[k].label} <ArrowUpRight className="h-3.5 w-3.5" /></Link>}
                bodyClassName="p-0"
              >
                <OppList rows={rows} showKind={false} />
              </Panel>
            );
          })}
        </div>
      ) : (
        <Panel title={`${visible.length} opportunit${visible.length === 1 ? 'y' : 'ies'}`} bodyClassName="p-0">
          <OppList rows={visible} showKind />
        </Panel>
      )}
    </div>
  );
}

function OppList({ rows, showKind }: { rows: OpportunityItem[]; showKind: boolean }) {
  return (
    <ul className="divide-y divide-line">
      {rows.map((o) => (
        <li key={o.id} className="flex flex-col gap-2 px-4 py-3 lg:flex-row lg:items-start lg:gap-4">
          <div className="min-w-0 flex-1">
            <div className="mb-1 flex flex-wrap items-center gap-1.5">
              {showKind && <Badge tone="opp">{OPP_KIND_LABELS[o.kind]}</Badge>}
              <OppStatusBadge status={o.status} />
              <SourceBadge source={o.source} />
              <span className="font-mono text-2xs text-muted">{o.id}</span>
            </div>
            <p className="text-sm font-medium text-ink">{o.title}</p>
            <p className="mt-0.5 text-sm text-muted">{o.detail}</p>
            <div className="mt-1 flex flex-wrap items-center gap-x-3 gap-y-1 text-xs text-muted">
              {o.url && <SiteUrl url={o.url} />}
              <span title={fmtDate(o.createdAt)}>Found {fmtRelative(o.createdAt)}</span>
              <span className="tabular-nums">Value {fmtNum(o.value)}</span>
              {showKind && <Link to={OPP_KIND_SCREEN[o.kind].href} className="text-signal hover:underline">{OPP_KIND_SCREEN[o.kind].label}</Link>}
            </div>
          </div>
          <div className="shrink-0">
            <OpportunityActions o={o} />
          </div>
        </li>
      ))}
    </ul>
  );
}
